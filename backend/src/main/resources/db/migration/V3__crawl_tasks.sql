CREATE TABLE crawl_source (
 id VARCHAR(40) PRIMARY KEY, name VARCHAR(100) NOT NULL, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 config_version INTEGER NOT NULL DEFAULT 0, min_interval_ms INTEGER NOT NULL DEFAULT 1500,
 next_request_at BIGINT NOT NULL DEFAULT 0, lease_token VARCHAR(36), lease_until BIGINT,
 schedule_enabled BOOLEAN NOT NULL DEFAULT FALSE, schedule_every_minutes INTEGER NOT NULL DEFAULT 1440,
 schedule_issn VARCHAR(9) NOT NULL DEFAULT '', schedule_page_size INTEGER NOT NULL DEFAULT 20,
 schedule_max_pages INTEGER NOT NULL DEFAULT 5, schedule_lookback_days INTEGER NOT NULL DEFAULT 1,
 next_schedule_at BIGINT NOT NULL DEFAULT 0, schedule_user_id VARCHAR(36) REFERENCES app_user(id)
);
