CREATE TABLE crawl_task (
 id VARCHAR(36) PRIMARY KEY, source_id VARCHAR(40) NOT NULL REFERENCES crawl_source(id),
 created_by VARCHAR(36) NOT NULL REFERENCES app_user(id), parent_task_id VARCHAR(36) REFERENCES crawl_task(id),
 scope_key VARCHAR(64) NOT NULL, issn VARCHAR(9) NOT NULL, query_text VARCHAR(200) NOT NULL, doi VARCHAR(300) NOT NULL,
 from_date VARCHAR(10) NOT NULL, until_date VARCHAR(10) NOT NULL, page_size INTEGER NOT NULL, max_pages INTEGER NOT NULL,
 mode VARCHAR(20) NOT NULL CHECK(mode IN ('BOUNDED','INCREMENTAL')), max_records INTEGER NOT NULL,
 from_publication_year INTEGER, to_publication_year INTEGER, completion_reason VARCHAR(60) NOT NULL DEFAULT '',

 state VARCHAR(20) NOT NULL CHECK(state IN ('PENDING','RUNNING','SUCCESS','FAILED','RETRYING','STOPPED')),
 runnable BOOLEAN NOT NULL DEFAULT FALSE, version INTEGER NOT NULL DEFAULT 0, attempt INTEGER NOT NULL DEFAULT 0,
 retry_count INTEGER NOT NULL DEFAULT 0, next_run_at BIGINT NOT NULL DEFAULT 0,
 lease_token VARCHAR(36), lease_until BIGINT, stop_requested BOOLEAN NOT NULL DEFAULT FALSE,
 next_cursor TEXT NOT NULL, committed_pages INTEGER NOT NULL DEFAULT 0,
 received INTEGER NOT NULL DEFAULT 0, inserted INTEGER NOT NULL DEFAULT 0, updated INTEGER NOT NULL DEFAULT 0,
 unchanged INTEGER NOT NULL DEFAULT 0, excluded INTEGER NOT NULL DEFAULT 0, conflicts INTEGER NOT NULL DEFAULT 0,
 publication_revision BIGINT, source_config_version INTEGER NOT NULL,
 error_code VARCHAR(60) NOT NULL DEFAULT '', error_message VARCHAR(2000) NOT NULL DEFAULT '',
 created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL, completed_at BIGINT
);
CREATE INDEX crawl_dispatch_idx ON crawl_task(state,runnable,next_run_at,created_at);
CREATE INDEX crawl_source_task_idx ON crawl_task(source_id,created_at);
CREATE TABLE crawl_checkpoint (
 source_id VARCHAR(40) NOT NULL REFERENCES crawl_source(id), scope_key VARCHAR(64) NOT NULL,
 issn VARCHAR(9) NOT NULL, query_text VARCHAR(200) NOT NULL, successful_until VARCHAR(10) NOT NULL,
 task_id VARCHAR(36) NOT NULL REFERENCES crawl_task(id), updated_at BIGINT NOT NULL,
 PRIMARY KEY(source_id,scope_key)
);
CREATE TABLE crawl_page (
 task_id VARCHAR(36) NOT NULL REFERENCES crawl_task(id), page_no INTEGER NOT NULL,
 attempt INTEGER NOT NULL, request_url TEXT NOT NULL, raw_json TEXT NOT NULL, response_checksum VARCHAR(64) NOT NULL,
 http_status INTEGER NOT NULL, etag VARCHAR(1000), last_modified VARCHAR(200), exclusions_json TEXT NOT NULL,
 import_task_id VARCHAR(36) REFERENCES import_task(id), revision BIGINT, received INTEGER NOT NULL,
 accepted INTEGER NOT NULL, excluded INTEGER NOT NULL, created_at BIGINT NOT NULL,
 PRIMARY KEY(task_id,page_no)
);
CREATE TABLE crawl_task_log (
 sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 task_id VARCHAR(36) NOT NULL REFERENCES crawl_task(id), attempt INTEGER NOT NULL,
 action VARCHAR(60) NOT NULL, before_state VARCHAR(20), after_state VARCHAR(20),
 message VARCHAR(2000) NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX crawl_log_task_idx ON crawl_task_log(task_id,sequence_no);
CREATE TABLE crawl_http_cache (
 url_hash VARCHAR(64) PRIMARY KEY, request_url TEXT NOT NULL, body TEXT NOT NULL,
 etag VARCHAR(1000), last_modified VARCHAR(200), expires_at BIGINT NOT NULL, stored_at BIGINT NOT NULL
);
