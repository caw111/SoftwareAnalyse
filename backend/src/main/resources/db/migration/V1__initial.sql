CREATE TABLE app_user (
 id VARCHAR(36) PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(300) NOT NULL, display_name VARCHAR(100) NOT NULL,
 role VARCHAR(20) NOT NULL CHECK (role IN ('USER','RESEARCHER','ADMIN')),
 created_at BIGINT NOT NULL
);
CREATE TABLE auth_session (
 token_hash VARCHAR(64) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id), expires_at BIGINT NOT NULL
);
CREATE INDEX session_expiry_idx ON auth_session(expires_at);
CREATE TABLE institution (id VARCHAR(80) PRIMARY KEY, name VARCHAR(200) NOT NULL);
CREATE TABLE scholar (
 id VARCHAR(80) PRIMARY KEY, name VARCHAR(100) NOT NULL,
 institution_id VARCHAR(80) REFERENCES institution(id), bio VARCHAR(2000) NOT NULL,
 simulated BOOLEAN NOT NULL
);
CREATE TABLE work (
 id VARCHAR(36) PRIMARY KEY, canonical_key VARCHAR(500) NOT NULL UNIQUE,
 type VARCHAR(12) NOT NULL CHECK (type IN ('PAPER','PATENT','PROJECT','AWARD')),
 title VARCHAR(1000) NOT NULL, search_text TEXT NOT NULL,
 date_value VARCHAR(10), date_kind VARCHAR(30) NOT NULL, date_precision VARCHAR(10), year INTEGER,
 doi VARCHAR(300), identifier VARCHAR(200), identifier_type VARCHAR(80), authority VARCHAR(200),
 abstract_text TEXT NOT NULL, venue VARCHAR(300) NOT NULL, citation_count INTEGER CHECK (citation_count >= 0),
 citation_source VARCHAR(200), oa_status VARCHAR(20) NOT NULL,
 simulated BOOLEAN NOT NULL, revision BIGINT NOT NULL, created_at BIGINT NOT NULL,
 details_json TEXT NOT NULL
);
CREATE INDEX work_filter_idx ON work(simulated,type,year,revision);
CREATE INDEX work_revision_idx ON work(revision);
CREATE INDEX work_doi_idx ON work(doi);
CREATE TABLE contributor (
 work_id VARCHAR(36) NOT NULL REFERENCES work(id), position INTEGER NOT NULL,
 scholar_id VARCHAR(80) REFERENCES scholar(id), name VARCHAR(100) NOT NULL, role VARCHAR(40) NOT NULL,
 institution_id VARCHAR(80) REFERENCES institution(id),
 PRIMARY KEY(work_id,position)
);
CREATE INDEX contributor_scholar_idx ON contributor(scholar_id,institution_id,work_id);
CREATE TABLE work_institution (
 work_id VARCHAR(36) NOT NULL REFERENCES work(id), institution_id VARCHAR(80) NOT NULL REFERENCES institution(id),
 PRIMARY KEY(work_id,institution_id)
);
CREATE TABLE work_field (
 work_id VARCHAR(36) NOT NULL REFERENCES work(id), field_name VARCHAR(100) NOT NULL,
 PRIMARY KEY(work_id,field_name)
);
CREATE INDEX work_field_name_idx ON work_field(field_name,work_id);
CREATE TABLE import_task (
 id VARCHAR(36) PRIMARY KEY, request_key VARCHAR(100) NOT NULL UNIQUE, request_hash VARCHAR(64) NOT NULL,
 source_name VARCHAR(200) NOT NULL, state VARCHAR(20) NOT NULL,
 received INTEGER NOT NULL, inserted INTEGER NOT NULL, duplicates INTEGER NOT NULL, revision BIGINT NOT NULL,
 created_by VARCHAR(36) NOT NULL REFERENCES app_user(id), created_at BIGINT NOT NULL
);
CREATE TABLE source_record (
 id VARCHAR(36) PRIMARY KEY, work_id VARCHAR(36) NOT NULL REFERENCES work(id),
 source_name VARCHAR(200) NOT NULL, source_key VARCHAR(200) NOT NULL, source_url VARCHAR(2000) NOT NULL,
 checksum VARCHAR(64) NOT NULL, raw_json TEXT NOT NULL, fetched_at BIGINT NOT NULL, revision BIGINT NOT NULL,
 UNIQUE(source_name,source_key,checksum)
);
CREATE INDEX source_work_idx ON source_record(work_id,revision);
CREATE TABLE source_observation (
 task_id VARCHAR(36) NOT NULL REFERENCES import_task(id), source_id VARCHAR(36) NOT NULL REFERENCES source_record(id),
 PRIMARY KEY(task_id,source_id)
);
CREATE TABLE claim (
 id VARCHAR(36) PRIMARY KEY, user_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 kind VARCHAR(20) NOT NULL CHECK (kind IN ('IDENTITY','PORTAL','OUTCOME','REVOKE')),
 target_id VARCHAR(80) NOT NULL, target_label VARCHAR(1000) NOT NULL,
 evidence TEXT NOT NULL, contribution_role VARCHAR(40) NOT NULL,
 state VARCHAR(30) NOT NULL, version INTEGER NOT NULL, material_version INTEGER NOT NULL,
 active_key VARCHAR(200) UNIQUE, reviewer_id VARCHAR(36) REFERENCES app_user(id), lease_until BIGINT,
 reason VARCHAR(2000) NOT NULL, created_at BIGINT NOT NULL, updated_at BIGINT NOT NULL
);
CREATE INDEX claim_user_idx ON claim(user_id,created_at);
CREATE INDEX claim_queue_idx ON claim(state,created_at);
CREATE TABLE portal_binding (
 user_id VARCHAR(36) PRIMARY KEY REFERENCES app_user(id), scholar_id VARCHAR(80) NOT NULL UNIQUE REFERENCES scholar(id)
);
CREATE TABLE outcome_binding (
 user_id VARCHAR(36) NOT NULL REFERENCES app_user(id), work_id VARCHAR(36) NOT NULL REFERENCES work(id),
 scholar_id VARCHAR(80) NOT NULL REFERENCES scholar(id), contribution_role VARCHAR(40) NOT NULL,
 PRIMARY KEY(user_id,work_id)
);
CREATE TABLE audit_event (
 sequence_no BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE,
 id VARCHAR(36) PRIMARY KEY, actor_id VARCHAR(36) NOT NULL REFERENCES app_user(id),
 object_id VARCHAR(80) NOT NULL, action VARCHAR(80) NOT NULL, before_state VARCHAR(40), after_state VARCHAR(40),
 reason VARCHAR(2000) NOT NULL, created_at BIGINT NOT NULL
);
CREATE INDEX audit_object_idx ON audit_event(object_id,created_at);
