def markdown(bs):
 out=[]
 def safe(s):
  parts=str(s).split('`')
  return '`'.join(v if i%2 else v.replace('<','&lt;').replace('>','&gt;') for i,v in enumerate(parts))
 for typ,value in bs:
  if typ=='h1':out.append('# '+value)
  elif typ=='h2':out.append('## '+value)
  elif typ=='p':out.append(safe(value))
  elif typ=='figure':out.append('![图 '+value[0]+']('+value[1]+')')
  elif typ=='table':
   head,rows=value
   fmt=lambda r:'| '+' | '.join(safe(v).replace('\n','<br>').replace('|','／') for v in r)+' |'
   out.append('\n'.join([fmt(head),fmt(['---']*len(head))]+[fmt(r) for r in rows]))
 return '\n\n'.join(out)+'\n'
